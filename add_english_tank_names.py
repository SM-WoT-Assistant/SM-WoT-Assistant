# Load tank data
with open("tank_slots_full.json", "r", encoding="utf-8") as f:
    tanks = json.load(f)

# Add English names
for tank_id, data in tanks.items():
    if tank_id in tank_names_english:
        data["name_english"] = tank_names_english[tank_id]
    else:
        # Try to guess from ID prefix
        if tank_id.startswith("R"):
            data["name_english"] = f"Soviet tank {tank_id}"
        elif tank_id.startswith("A") or tank_id.startswith("M"):
            data["name_english"] = f"American tank {tank_id}"
        elif tank_id.startswith("G") or tank_id.startswith("Pz"):
            data["name_english"] = f"German tank {tank_id}"
        elif tank_id.startswith("GB"):
            data["name_english"] = f"British tank {tank_id}"
        elif tank_id.startswith("F") or tank_id.startswith("AMX"):
            data["name_english"] = f"French tank {tank_id}"
        elif tank_id.startswith("Ch"):
            data["name_english"] = f"Chinese tank {tank_id}"
        else:
            data["name_english"] = tank_id

# Save
with open("tank_slots_full.json", "w", encoding="utf-8") as f:
    json.dump(tanks, f, ensure_ascii=False, indent=2)

